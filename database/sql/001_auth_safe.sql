-- Crea rol/usuario solo si no existen y agrega únicamente columnas faltantes.

BEGIN;

CREATE TABLE IF NOT EXISTS rol (
    id_rol BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(50),
    nombre VARCHAR(100),
    descripcion TEXT,
    estado BOOLEAN DEFAULT TRUE,
    created_at TIMESTAMP(0) WITHOUT TIME ZONE NULL,
    updated_at TIMESTAMP(0) WITHOUT TIME ZONE NULL
);

ALTER TABLE rol ADD COLUMN IF NOT EXISTS codigo VARCHAR(50);
ALTER TABLE rol ADD COLUMN IF NOT EXISTS nombre VARCHAR(100);
ALTER TABLE rol ADD COLUMN IF NOT EXISTS descripcion TEXT;
ALTER TABLE rol ADD COLUMN IF NOT EXISTS estado BOOLEAN DEFAULT TRUE;
ALTER TABLE rol ADD COLUMN IF NOT EXISTS created_at TIMESTAMP(0) WITHOUT TIME ZONE NULL;
ALTER TABLE rol ADD COLUMN IF NOT EXISTS updated_at TIMESTAMP(0) WITHOUT TIME ZONE NULL;

CREATE TABLE IF NOT EXISTS usuario (
    id_usuario BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_empresa BIGINT NULL,
    id_rol BIGINT NULL,
    nombre VARCHAR(150),
    correo VARCHAR(255),
    password_hash VARCHAR(255),
    estado BOOLEAN DEFAULT TRUE,
    email_verified_at TIMESTAMP(0) WITHOUT TIME ZONE NULL,
    remember_token VARCHAR(100) NULL,
    ultimo_acceso TIMESTAMP(0) WITHOUT TIME ZONE NULL,
    created_at TIMESTAMP(0) WITHOUT TIME ZONE NULL,
    updated_at TIMESTAMP(0) WITHOUT TIME ZONE NULL
);

ALTER TABLE usuario ADD COLUMN IF NOT EXISTS id_empresa BIGINT NULL;
ALTER TABLE usuario ADD COLUMN IF NOT EXISTS id_rol BIGINT NULL;
ALTER TABLE usuario ADD COLUMN IF NOT EXISTS nombre VARCHAR(150);
ALTER TABLE usuario ADD COLUMN IF NOT EXISTS correo VARCHAR(255);
ALTER TABLE usuario ADD COLUMN IF NOT EXISTS password_hash VARCHAR(255);
ALTER TABLE usuario ADD COLUMN IF NOT EXISTS estado BOOLEAN DEFAULT TRUE;
ALTER TABLE usuario ADD COLUMN IF NOT EXISTS email_verified_at TIMESTAMP(0) WITHOUT TIME ZONE NULL;
ALTER TABLE usuario ADD COLUMN IF NOT EXISTS remember_token VARCHAR(100) NULL;
ALTER TABLE usuario ADD COLUMN IF NOT EXISTS ultimo_acceso TIMESTAMP(0) WITHOUT TIME ZONE NULL;
ALTER TABLE usuario ADD COLUMN IF NOT EXISTS created_at TIMESTAMP(0) WITHOUT TIME ZONE NULL;
ALTER TABLE usuario ADD COLUMN IF NOT EXISTS updated_at TIMESTAMP(0) WITHOUT TIME ZONE NULL;

