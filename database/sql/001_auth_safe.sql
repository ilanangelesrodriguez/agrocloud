-- Índices únicos solo cuando los datos actuales lo permiten.
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM rol
        WHERE codigo IS NOT NULL
        GROUP BY codigo
        HAVING COUNT(*) > 1
    ) AND NOT EXISTS (
        SELECT 1 FROM pg_indexes
        WHERE schemaname = current_schema()
          AND indexname = 'rol_codigo_unique'
    ) THEN
        EXECUTE 'CREATE UNIQUE INDEX rol_codigo_unique ON rol (codigo)';
    END IF;
END $$;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM usuario
        WHERE correo IS NOT NULL
        GROUP BY LOWER(correo)
        HAVING COUNT(*) > 1
    ) AND NOT EXISTS (
        SELECT 1 FROM pg_indexes
        WHERE schemaname = current_schema()
          AND indexname = 'usuario_correo_unique'
    ) THEN
        EXECUTE 'CREATE UNIQUE INDEX usuario_correo_unique ON usuario (LOWER(correo)) WHERE correo IS NOT NULL';
    END IF;
END $$;

-- FK de rol: se agrega únicamente si no hay datos huérfanos y aún no existe.
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM pg_constraint
        WHERE conname = 'usuario_id_rol_foreign'
    ) AND NOT EXISTS (
        SELECT 1
        FROM usuario u
        WHERE u.id_rol IS NOT NULL
          AND NOT EXISTS (SELECT 1 FROM rol r WHERE r.id_rol = u.id_rol)
    ) THEN
        ALTER TABLE usuario
            ADD CONSTRAINT usuario_id_rol_foreign
            FOREIGN KEY (id_rol) REFERENCES rol(id_rol);
    END IF;
END $$;

COMMIT;
